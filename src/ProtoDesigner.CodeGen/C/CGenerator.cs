    private static string EmitReadme(IReadOnlyList<ProtocolIr> buses, GeneratorOptions options)
    {
        var prefix = Prefix(options);
        var sb = new StringBuilder();

        sb.AppendLine($"# {buses[0].ProjectName} — generated C codec");
        sb.AppendLine();
        sb.AppendLine("Generated by ProtoDesigner. Do not edit these files; change the `.pdproj` and regenerate.");
        sb.AppendLine();
        sb.AppendLine($"- Buses: {string.Join(", ", buses.Select(b => $"`{b.BusName}`"))}");
        sb.AppendLine($"- Symbol prefix: `{prefix}_`");
        sb.AppendLine("- Standard: C99, header-only, no allocation. Compiles as C or as C++.");
        sb.AppendLine();
        sb.AppendLine("C has no namespaces, so every symbol carries the prefix above. It compiles under a C++");
        sb.AppendLine("compiler too — the headers wrap themselves in `extern \"C\"` — so one definition serves a C");
        sb.AppendLine("module and a C++ module without either having to care what the other is written in.");
        sb.AppendLine();
        sb.AppendLine("## Files");
        sb.AppendLine();
        sb.AppendLine("| File | Contents |");
        sb.AppendLine("|---|---|");
        sb.AppendLine($"| `{CRuntimeHeader.FileName}` | The bit cursor everything else is built on |");
        sb.AppendLine($"| `{TypesFileName(options)}` | Shared enums and structs — project-wide, so declared once |");
        foreach (var ir in buses)
            sb.AppendLine($"| `{FileStem(ir.BusName)}.h` | Messages on bus `{ir.BusName}` and their conversions |");
        sb.AppendLine();

        sb.AppendLine("## Messages");
        sb.AppendLine();
        sb.AppendLine("| Bus | Message | Message id | Size | Fields |");
        sb.AppendLine("|---|---|---|---|---|");
        foreach (var ir in buses)
            foreach (var m in ir.Messages)
                sb.AppendLine($"| `{ir.BusName}` | `{m.Name}` | {(m.WireId?.ToString(CultureInfo.InvariantCulture) ?? "—")} "
                    + $"| {(m.MinBits == m.MaxBits ? $"{(m.MaxBits + 7) / 8} B" : $"{(m.MinBits + 7) / 8}..{(m.MaxBits + 7) / 8} B")} "
                    + $"| {m.Fields.Count} |");
        sb.AppendLine();

        var first = buses[0].Messages.FirstOrDefault();
        if (first is not null)
        {
            var type = CNaming.TypeName(prefix, first.Name);
            var maxBytes = CNaming.MacroName(prefix, first.Name, "MAX_BYTES");

            sb.AppendLine("## Usage");
            sb.AppendLine();
            sb.AppendLine("```c");
            sb.AppendLine($"#include \"{FileStem(buses[0].BusName)}.h\"");
            sb.AppendLine();
            sb.AppendLine("/* The struct is the HOST representation: plain fields, no packing, no scaling. */");
            sb.AppendLine($"{type} msg;");
            sb.AppendLine("/* ... populate msg ... */");
            sb.AppendLine();
            sb.AppendLine("/* Host -> wire. */");
            sb.AppendLine($"uint8_t wire[{maxBytes}];");
            sb.AppendLine($"size_t written = {CNaming.FunctionName(prefix, first.Name, "ConvertToWire")}(&msg, wire, sizeof(wire));");
            sb.AppendLine("if (written == 0) { /* buffer too small */ }");
            sb.AppendLine();
            sb.AppendLine("/* Wire -> host. */");
            sb.AppendLine($"{type} parsed;");
            sb.AppendLine($"pd_decode_result_t status = {CNaming.FunctionName(prefix, first.Name, "ConvertToHost")}(wire, written, &parsed);");
            sb.AppendLine("if (!status.ok) { /* truncated frame */ }");
            sb.AppendLine("```");
            sb.AppendLine();
        }

        sb.AppendLine("## Finding a field without storing an offset");
        sb.AppendLine();
        sb.AppendLine("Checksums and CRCs are not modelled — a checksum is an ordinary field you fill in. What is");
        sb.AppendLine("generated is the size information needed to place one, regenerated on every edit:");
        sb.AppendLine();
        sb.AppendLine("```c");
        sb.AppendLine("/* <TYPE>_ON_WIRE_BYTES per type, <Msg>_OnWireLength(msg) per message. */");
        if (first is not null)
            sb.AppendLine($"size_t len = {CNaming.FunctionName(prefix, first.Name, "OnWireLength")}(&msg);");
        sb.AppendLine("/* a trailing field then sits at len - <TYPE>_ON_WIRE_BYTES */");
        sb.AppendLine("```");

        return sb.ToString();
    }
